create policy "profiles_select_authenticated" on public.profiles
for select to authenticated using (true);
create policy "profiles_update_own" on public.profiles
for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

create policy "courses_select_authenticated" on public.courses
for select to authenticated using (true);
create policy "courses_insert_educator" on public.courses
for insert to authenticated with check (
    educator_id = auth.uid() and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'educator')
);
create policy "courses_update_own" on public.courses
for update to authenticated using (educator_id = auth.uid()) with check (educator_id = auth.uid());
create policy "courses_delete_own" on public.courses
for delete to authenticated using (educator_id = auth.uid());

create policy "lessons_select_authenticated" on public.lessons
for select to authenticated using (true);
create policy "lessons_insert_own_course" on public.lessons
for insert to authenticated with check (
    exists (select 1 from public.courses c where c.id = course_id and c.educator_id = auth.uid())
);
create policy "lessons_update_own_course" on public.lessons
for update to authenticated using (
    exists (select 1 from public.courses c where c.id = course_id and c.educator_id = auth.uid())
) with check (
    exists (select 1 from public.courses c where c.id = course_id and c.educator_id = auth.uid())
);

