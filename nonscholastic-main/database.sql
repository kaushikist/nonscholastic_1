-- Nonscholastic Supabase database
-- Run this file in Supabase SQL Editor.
-- Safe for the browser: frontend code must use only the publishable key, never a service-role key.

create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    full_name text,
    email text,
    role text not null default 'learner'
        check (role in ('learner', 'educator')),
    bio text,
    profile_image text,
    created_at timestamp with time zone default now()
);

create table if not exists public.courses (
    id bigint generated by default as identity primary key,
    educator_id uuid not null references public.profiles(id) on delete cascade,
    title text not null,
    description text,
    category text,
    level text,
    thumbnail text,
    duration text,
    created_at timestamp with time zone default now()
);

create table if not exists public.lessons (
    id bigint generated by default as identity primary key,
    course_id bigint not null references public.courses(id) on delete cascade,
    title text not null,
    description text,
    video_url text,
    lesson_order integer default 1,
    created_at timestamp with time zone default now()
);

create table if not exists public.enrollments (
    id bigint generated by default as identity primary key,
    learner_id uuid not null references public.profiles(id) on delete cascade,
    course_id bigint not null references public.courses(id) on delete cascade,
    enrolled_at timestamp with time zone default now(),
    unique (learner_id, course_id)
);

create table if not exists public.progress (
    id bigint generated by default as identity primary key,
    learner_id uuid not null references public.profiles(id) on delete cascade,
    lesson_id bigint not null references public.lessons(id) on delete cascade,
    completed boolean default false,
    completed_at timestamp with time zone,
    unique (learner_id, lesson_id)
);

create table if not exists public.saved_courses (
    id bigint generated by default as identity primary key,
    learner_id uuid not null references public.profiles(id) on delete cascade,
    course_id bigint not null references public.courses(id) on delete cascade,
    saved_at timestamp with time zone default now(),
    unique (learner_id, course_id)
);

create table if not exists public.sessions (
    id bigint generated by default as identity primary key,
    educator_id uuid not null references public.profiles(id) on delete cascade,
    course_id bigint references public.courses(id) on delete cascade,
    title text not null,
    description text,
    session_date timestamp with time zone not null,
    meeting_link text,
    created_at timestamp with time zone default now()
);

create table if not exists public.messages (
    id bigint generated by default as identity primary key,
    sender_id uuid not null references public.profiles(id) on delete cascade,
    receiver_id uuid not null references public.profiles(id) on delete cascade,
    message text not null,
    created_at timestamp with time zone default now()
);

create table if not exists public.reviews (
    id bigint generated by default as identity primary key,
    learner_id uuid not null references public.profiles(id) on delete cascade,
    course_id bigint not null references public.courses(id) on delete cascade,
    rating integer not null check (rating between 1 and 5),
    comment text,
    created_at timestamp with time zone default now(),
    unique (learner_id, course_id)
);

-- Automatically create a profile after Supabase Auth creates a user.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.profiles (id, full_name, email, role)
    values (
        new.id,
        coalesce(new.raw_user_meta_data->>'full_name', ''),
        new.email,
        coalesce(new.raw_user_meta_data->>'role', 'learner')
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row
    execute procedure public.handle_new_user();

